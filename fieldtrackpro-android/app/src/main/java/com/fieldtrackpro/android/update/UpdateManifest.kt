package com.fieldtrackpro.android.update

import com.google.gson.Gson
import com.google.gson.annotations.SerializedName
import java.net.URI

/**
 * Release manifest published next to the APK (static JSON on the existing free Vercel site):
 *
 *   https://fieldtrack-pro-rosy.vercel.app/downloads/app-update.json
 *
 * {
 *   "schema": 1,
 *   "packageName": "com.fieldtrackpro.android",
 *   "versionCode": 7,
 *   "versionName": "1.3.1",
 *   "apkUrl": "https://fieldtrack-pro-rosy.vercel.app/downloads/releases/FieldTrackPro-1.3.1-7.apk",
 *   "apkSha256": "<64 hex chars>",
 *   "apkSizeBytes": 23456789,
 *   "minSupportedVersionCode": 6,
 *   "mandatory": false,
 *   "releaseNotes": ["Faster dashboard", "Fixes"],
 *   "publishedAt": "2026-11-22"
 * }
 *
 * Generated by tools/make_update_manifest.py; see design-review/IN_APP_UPDATES.md.
 */
data class UpdateManifest(
    @SerializedName("schema") val schema: Int = 1,
    @SerializedName("packageName") val packageName: String? = null,
    @SerializedName("versionCode") val versionCode: Long = 0,
    @SerializedName("versionName") val versionName: String? = null,
    @SerializedName("apkUrl") val apkUrl: String? = null,
    @SerializedName("apkSha256") val apkSha256: String? = null,
    @SerializedName("apkSizeBytes") val apkSizeBytes: Long? = null,
    @SerializedName("minSupportedVersionCode") val minSupportedVersionCode: Long = 0,
    @SerializedName("mandatory") val mandatory: Boolean = false,
    @SerializedName("releaseNotes") val releaseNotes: List<String>? = null,
    @SerializedName("publishedAt") val publishedAt: String? = null
) {
    companion object {
        const val SUPPORTED_SCHEMA = 1
        private val SHA256_HEX = Regex("^[0-9a-fA-F]{64}$")
        private val gson = Gson()

        fun parse(json: String): UpdateManifest? = try {
            gson.fromJson(json, UpdateManifest::class.java)
        } catch (e: Exception) {
            null
        }

        /** True when [url] is https and its host is one of [allowedHosts] (exact match, case-insensitive). */
        fun isTrustedUrl(url: String?, allowedHosts: Set<String>): Boolean {
            if (url.isNullOrBlank()) return false
            return try {
                val uri = URI(url)
                uri.scheme.equals("https", ignoreCase = true) &&
                    uri.userInfo == null &&
                    uri.host != null &&
                    allowedHosts.any { it.equals(uri.host, ignoreCase = true) }
            } catch (e: Exception) {
                false
            }
        }

        fun isSha256Hex(value: String?): Boolean = value != null && SHA256_HEX.matches(value)
    }

    /** Structural validation. Returns the reason the manifest must be ignored, or null when it is usable. */
    fun problem(expectedPackage: String, allowedHosts: Set<String>): String? = when {
        schema != SUPPORTED_SCHEMA -> "Unsupported manifest schema $schema"
        packageName != expectedPackage -> "Manifest is for another app"
        versionCode <= 0 -> "Missing versionCode"
        versionName.isNullOrBlank() -> "Missing versionName"
        !isTrustedUrl(apkUrl, allowedHosts) -> "APK URL is not an allowed https address"
        !isSha256Hex(apkSha256) -> "Missing or malformed SHA-256"
        apkSizeBytes != null && apkSizeBytes <= 0 -> "Invalid APK size"
        minSupportedVersionCode < 0 || minSupportedVersionCode > versionCode -> "minSupportedVersionCode is above the published version"
        else -> null
    }
}
